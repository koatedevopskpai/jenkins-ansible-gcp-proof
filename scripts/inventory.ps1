<#
.SYNOPSIS
    Generate ansible/inventory/hosts.ini from terraform outputs.
.DESCRIPTION
    Reads the Jenkins VM name/IP from terraform and writes an inventory that
    connects over SSH via an IAP tunnel (no public SSH exposure required).
#>
[CmdletBinding()]
param(
    [string]$SshUser = $env:USERNAME,
    [string]$Zone = "us-central1-a"
)

$ErrorActionPreference = 'Stop'
$here = $PSScriptRoot
$tfDir = [System.IO.Path]::GetFullPath((Join-Path $here '..\infra\terraform\environments\dev'))
$invFile = [System.IO.Path]::GetFullPath((Join-Path $here '..\ansible\inventory\hosts.ini'))

$vm = (terraform -chdir=$tfDir output -raw jenkins_vm_name).Trim()
$ip = (terraform -chdir=$tfDir output -raw jenkins_vm_ip).Trim()
$project = (gcloud config get-value project 2>$null).Trim()

$proxy = "gcloud compute start-iap-tunnel $vm %p --listen-on-stdin --zone $Zone --project $project --iap-tunnel-disable-connection-check"

$content = @"
# Generated by scripts/inventory.ps1 - do not edit by hand.
[jenkins]
jenkins-controller ansible_host=$ip ansible_user=$SshUser

[jenkins:vars]
ansible_python_interpreter=/usr/bin/python3
ansible_ssh_common_args=-o ProxyCommand="$proxy"
"@

Set-Content -LiteralPath $invFile -Value $content -Encoding UTF8
Write-Host "Wrote $invFile (host $ip as $SshUser via IAP)"
